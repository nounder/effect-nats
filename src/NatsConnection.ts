/**
 * Native NATS client connection built on the `NatsProtocol` wire codec.
 *
 * One connection multiplexes publishes, subscriptions and requests. It reconnects across the
 * configured (and server-advertised) servers, resubscribes, and replays publishes buffered while
 * disconnected.
 *
 * Like `@effect/sql-pg`, the session drives a Node `Duplex` (`node:net`, or `node:tls`) directly
 * and decodes frames synchronously as they arrive. `ws://` and `wss://` servers go through
 * `effect/socket` WebSockets, adapted to the same `Duplex` interface.
 */
